const controlRecipes = async function () {
  try {
    const id = window.location.hash.slice(1); //using slice to remove # in front of id
    //console.log(id);

    if (!id) return;
    recipeView.renderSpinner();

    // 0) Update results view to mark selected search result
    resultsView.update(model.getSearchResultsPage());

    // 1) Updating bookmarks view
    bookmarksView.update(model.state.bookmarks);

    // 2) Loading recipe
    await model.loadRecipe(id); //loadrecipe is async func,it is going to return promise.to avoid that promise before we can move on in next step in excution of this aync func
    // loadrecipe func here does return anything,so not storing any result into new variable.instead will get accsess to state.recipe

    // 3) Rendering recipe
    recipeView.render(model.state.recipe);
  } catch (err) {
    recipeView.renderError();
  }
};
